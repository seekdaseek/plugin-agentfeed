#!/usr/bin/env node
// gen-tickers.mjs — src/tickers.ts, the equity-24h ticker allowlist.
//
// equity-24h must fire only for a real US stock or index ticker, never for a crypto
// symbol, so the plugin matches against the tickers the service actually quotes:
// every market its TradFi collector classifies as stock or index (venue metadata, see
// tools/tradfi.js on the service) plus its tokenized-stock (xStock) peg tape.
//
// AMBIGUOUS tickers match bare only beside a stock-context word, otherwise only as
// $TICKER or TICKERx: single letters, English words (/usr/share/dict/words: META,
// COIN, NOW ...), and tickers that are ALSO a crypto perp base on OKX, Hyperliquid or
// Bybit (BB, QNT, STX ...), because "COIN" or "STX" in a crypto chat is not a stock.
//
// usage: node gen-tickers.mjs <dump.json>
//   dump.json = {"as_of": ..., "source": ..., "tickers": [...]}, written on the service
//   box from funding-radar.json tradfi.markets (asset_class stock|index) + pegwatch.
import fs from 'node:fs';

const dump = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const tickers = [...new Set(dump.tickers.map((t) => t.toUpperCase()))].sort();
if (tickers.length < 100) throw new Error(`only ${tickers.length} tickers: wrong dump?`);

const j = (u, o) => fetch(u, o).then((r) => { if (!r.ok) throw new Error(`${u} HTTP ${r.status}`); return r.json(); });
const okx = (await j('https://www.okx.com/api/v5/public/instruments?instType=SWAP')).data
  .filter((i) => i.instCategory === '1').map((i) => i.instFamily.split('-')[0]);
const hl = (await j('https://api.hyperliquid.xyz/info', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ type: 'meta' }) }))
  .universe.map((u) => u.name);
const by = [];
for (let cursor = '', page = 0; page < 5; page++) {
  const r = (await j(`https://api.bybit.com/v5/market/instruments-info?category=linear&limit=1000${cursor ? `&cursor=${cursor}` : ''}`)).result;
  by.push(...r.list.filter((i) => !i.symbolType).map((i) => i.baseCoin));
  if (!r.nextPageCursor) break; cursor = r.nextPageCursor;
}
// Hyperliquid prefixes 1000x contracts with a lowercase k (kPEPE); the others with 1000.
const crypto = new Set([...okx, ...hl, ...by].map((s) => s.replace(/^k(?=[A-Z])/, '').toUpperCase().replace(/^1000+/, '')));
if (!crypto.has('BTC') || !crypto.has('HYPE')) throw new Error('crypto base list looks wrong');
const words = new Set(fs.readFileSync('/usr/share/dict/words', 'utf8').split('\n').map((w) => w.toUpperCase()));
if (!words.has('COIN') || words.has('TSLA')) throw new Error('dictionary control failed');

const leak = tickers.filter((t) => ['BTC', 'ETH', 'SOL', 'HYPE', 'XRP', 'DOGE'].includes(t));
if (leak.length) throw new Error(`crypto majors in the stock list: ${leak}`);
const ambiguous = tickers.filter((t) => t.length === 1 || words.has(t) || crypto.has(t));

const list = (a) => a.map((t) => `'${t}'`).join(', ');
fs.writeFileSync('src/tickers.ts', `// GENERATED by gen-tickers.mjs from the service's ${dump.as_of} TradFi snapshot. Do not edit.
// ${dump.source}

/** Every US stock or index ticker equity-24h quotes (${tickers.length}). */
export const EQUITY_TICKERS: ReadonlySet<string> = new Set([${list(tickers)}]);

/** Tickers that are also a word, a single letter or a crypto perp base (${ambiguous.length}): bare only beside a stock word. */
export const AMBIGUOUS_TICKERS: ReadonlySet<string> = new Set([${list(ambiguous)}]);
`);
console.log(`src/tickers.ts: ${tickers.length} tickers, ${ambiguous.length} ambiguous (${ambiguous.filter((t) => crypto.has(t)).join(' ')} clash with crypto)`);
